test("darwin: absence first reported after the removal deadline does not permit start", async t => {
    const f = fixture(t);
    f.launchd.delayPolls = 0;
    const native = (args, options) => {
        const output = f.native(args, options);
        if (options?.allowAbsent && f.events.includes("unloaded")) {
            // Simulate a synchronous native reply that arrives after expiry.
            const start = performance.now();
            while (performance.now() - start < 20) {}
        }
        return output;
    };
    await assert.rejects(f.apply(ref, { native, stopTimeoutMs: 10 }), /Timed out waiting.*removal/);
    assert.deepEqual(f.actions, []);
    assert(!existsSync(f.stampFile));
});

test("darwin: native removal commands share the remaining monotonic budget", async t => {
    const f = fixture(t);
    let clock = 0;
    const timeouts = [];
    const native = (args, options) => {
        if (options?.timeoutMs !== undefined) {
            timeouts.push(options.timeoutMs);
            assert(options.timeoutMs <= 100 - clock);
            clock += 10;
        }
        return f.native(args, options);
    };
    await f.apply(ref, { native, stopTimeoutMs: 100, stopNow: () => clock });
    assert.deepEqual(timeouts, [100, 90, 80, 70, 60, 50]);
    assert.deepEqual(f.actions, ["start"]);
});

