const source = "powerfooI/roamgate";
const ref = "v0.7.15";
const password = 'mock & $HOME `printf wrong` # \\ " \' end';
const marker = "Generated by roamgate service install.";
const shell = 'set -a; if [ -f "$1" ]; then . "$1"; fi; set +a; exec "$2"';
const quote = value => `"${value.replace(/[\\"$`]/g, character => `\\${character}`)}"`;

function fixture(t, options = {}) {
    const home = mkdtempSync(join(tmpdir(), "roamgate-test-"));
    t.after(() => rmSync(home, { recursive: true, force: true }));
    const platform = options.platform ?? "darwin";
    const stateHome = join(home, ".local", "state");
    const envFile = join(home, ".config", "roamgate", "roamgate.env");
    const ownerFile = join(stateHome, "chezmoi", "herdr-plugins");
    const stampFile = join(stateHome, "chezmoi", "roamgate");
    const definition = platform === "darwin" ? join(home, "Library", "LaunchAgents", "dev.roamgate.plist") : join(home, ".config", "systemd", "user", "roamgate.service");
    mkdirSync(dirname(envFile), { recursive: true });
    mkdirSync(dirname(ownerFile), { recursive: true });
    mkdirSync(dirname(definition), { recursive: true });
    if (options.owned !== false) writeFileSync(ownerFile, `${source}\t${ref}\n`, { mode: 0o600 });
    const plugin = { plugin_id: "roamgate", enabled: options.disabled !== true, version: ref.slice(1),
        plugin_root: join(home, "managed", ref), source: { kind: "github", owner: "powerfooI", repo: "roamgate", requested_ref: ref } };
    const server = { running: false, password, version: ref.slice(1), origin: "http://192.0.2.10:8788" };
    const controls = { fail: false, hang: false, oldVersion: false, open: false, rejectPassword: false, healthBody: null, noCookie: false,
        dropIns: "", foreignDefinition: false, earlyOfflineChecks: 0 };
    const actions = [], commands = [], nativeCalls = [], logs = [], requests = [], events = [];
    // A plist on disk is not proof that launchd has removed its active job.
    const launchd = { loaded: options.loaded ?? options.defined !== false, stopping: false,
        remaining: 0, delayPolls: 3, neverUnloads: false, bootoutError: false, probeError: false,
        probes: 0, reappearAtProbe: null, reappearAfterUnload: false };
    const unitPaths = [dirname(definition), join(home, "etc", "systemd", "user")];
    let plist;
    function writeDefinition(binary = join(plugin.plugin_root, "server", "roamgate")) {
        if (platform === "darwin") {
            plist = { Label: "dev.roamgate", ProgramArguments: ["/bin/sh", "-c", shell, "roamgate-service", envFile, binary],
                RunAtLoad: true, KeepAlive: true, ThrottleInterval: 2, ProcessType: "Background",
                StandardOutPath: join(home, "Library", "Logs", "roamgate.stdout.log"),
                StandardErrorPath: join(home, "Library", "Logs", "roamgate.stderr.log") };
            writeFileSync(definition, `<!-- ${marker} -->\n`);
        } else writeFileSync(definition, `# ${marker}
[Unit]
Description=Roamgate
Wants=network-online.target
After=network-online.target

[Service]
Type=simple
EnvironmentFile=-${envFile}
ExecStart=${binary}
Restart=always
RestartSec=2
TimeoutStopSec=15

[Install]
WantedBy=default.target
`);
    }
    if (options.defined !== false) writeDefinition();
    function configure(secret = password, host = "192.0.2.10") {
        writeFileSync(envFile, `HOST=${quote(host)}\nPORT=8788\nROAMGATE_PASSWORD=${quote(secret)}\n`, { mode: 0o600 });
    }
    configure();
    function beginBootout() {
        events.push("bootout");
        launchd.stopping = true;
        launchd.remaining = launchd.delayPolls;
        server.running = false;
    }
    function native(args) {
        nativeCalls.push(args);
        if (args[0] === "launchctl") {
            const target = `gui/${process.getuid()}/dev.roamgate`;
            if (args[1] === "bootout") {
                assert.deepEqual(args, ["launchctl", "bootout", target]);
                assert(launchd.loaded);
                if (launchd.bootoutError) throw new Error("mock bootout failed");
                beginBootout();
                return "";
            }
            assert.deepEqual(args, ["launchctl", "print", target]);
            launchd.probes++;
            if (launchd.probes === launchd.reappearAtProbe || (launchd.reappearAfterUnload &&
                events.includes("unloaded") && events.at(-1) === "print:absent")) {
                launchd.loaded = true;
                events.push("reappeared");
            }
            if (launchd.stopping) {
                if (launchd.probeError) throw new Error("mock launchd inspection failed");
                if (!launchd.neverUnloads && launchd.remaining-- <= 0) {
                    launchd.loaded = false;
                    launchd.stopping = false;
                    events.push("unloaded");
                }
            }
            events.push(launchd.loaded ? "print:loaded" : "print:absent");
            return launchd.loaded ? `path = ${controls.foreignDefinition ? join(home, "custom.plist") : definition}\n` : "";
        }
        if (args[0] === "plutil") {
            assert.deepEqual(args, ["plutil", "-convert", "json", "-o", "-", definition]);
            return JSON.stringify(plist);
        }
        if (args[0] === "busctl") {
            assert.deepEqual(args, ["busctl", "--user", "--json=short", "get-property", "org.freedesktop.systemd1",
                "/org/freedesktop/systemd1", "org.freedesktop.systemd1.Manager", "UnitPath"]);
            return JSON.stringify({ type: "as", data: unitPaths });
        }
        assert.deepEqual(args, ["systemctl", "--user", "show", "roamgate.service", "--property=FragmentPath", "--property=DropInPaths"]);
        return `FragmentPath=${controls.foreignDefinition ? "/etc/systemd/user/roamgate.service" : existsSync(definition) ? definition : ""}\nDropInPaths=${controls.dropIns}\n`;
    }
    function run(args) {
        commands.push(args);
        if (args[1] === "list") {
            assert.deepEqual(args, ["plugin", "list", "--json", "--plugin", "roamgate"]);
            return JSON.stringify({ result: { plugins: [plugin] } });
        }
        if (args[1] === "action") {
            assert.deepEqual(args, ["plugin", "action", "invoke", "start", "--plugin", "roamgate"]);
            actions.push("start");
            events.push("start");
            const launchdRace = platform === "darwin" && launchd.loaded;
            // Model the actual upstream install --force race: bootout returns
            // while the job is still stopping, then immediate bootstrap fails.
            if (launchdRace) beginBootout();
            const log = { log_id: `mock-${logs.length + 1}`, plugin_id: "roamgate", action_id: "start", status: "running", exit_code: null, polls: 0, launchdRace };
            logs.push(log);
            return JSON.stringify({ result: { log } });
        }
        assert.deepEqual(args, ["plugin", "log", "list", "--plugin", "roamgate", "--limit", "100"]);
        const log = logs.at(-1);
        if (++log.polls > 1 && !controls.hang) {
            const failed = controls.fail || log.launchdRace;
            log.status = failed ? "failed" : "succeeded";
            log.exit_code = log.launchdRace ? 5 : controls.fail ? 1 : 0;
            if (!failed) {
                if (platform === "darwin") launchd.loaded = true;
                const config = loadConfig(envFile);
                Object.assign(server, { running: true, origin: config.origin, password: config.env.ROAMGATE_PASSWORD,
                    version: controls.oldVersion ? "0.7.14" : plugin.version });
                writeDefinition();
            }
        }
        return JSON.stringify({ result: { logs } });
    }
    async function request(url, init = {}) {
        assert(!url.includes(password), "password must never be placed in URLs");
        requests.push(new URL(url).pathname);
        if (!server.running || new URL(url).origin !== server.origin) throw new Error("mock offline");
        if (new URL(url).pathname === "/api/login") {
            assert.equal(init.method, "POST");
            const allowed = !controls.rejectPassword && JSON.parse(init.body).password === server.password;
            return Response.json({ ok: allowed }, { status: allowed ? 200 : 401,
                headers: allowed && !controls.noCookie ? { "set-cookie": "herdr_auth=mock-session; HttpOnly; Path=/" } : {} });
        }
        assert.equal(new URL(url).pathname, "/api/health");
        if (controls.earlyOfflineChecks > 0) { controls.earlyOfflineChecks--; throw new Error("mock not ready yet"); }
        const allowed = controls.open || init.headers?.cookie === "herdr_auth=mock-session";
        return Response.json(allowed ? controls.healthBody ?? { ok: true, version: server.version, auth_required: !controls.open } : {}, { status: allowed ? 200 : 401 });
    }
    const apply = (wanted = ref, extra = {}) => reconcile(wanted, { home, stateHome, platform, run, native, request,
        wait: async () => {}, healthTimeoutMs: 0, ...extra });
    return { home, envFile, ownerFile, stampFile, definition, plugin, server, controls, actions, commands, nativeCalls, requests, unitPaths, launchd, events,
        apply, configure, native, get plist() { return plist; },
        installAt(value) { plugin.source.requested_ref = value; plugin.version = value.slice(1); plugin.plugin_root = join(home, "managed", value); writeFileSync(ownerFile, `${source}\t${value}\n`); } };
}

