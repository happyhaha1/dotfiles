test("native launchd absence requires the exact not-found exit and message", () => {
    const print = ["launchctl", "print", `gui/${process.getuid()}/dev.roamgate`];
    const invoke = (args, exitCode, stdout, stderr, allowAbsent = true) => runNative(args, {
        allowAbsent, spawn: () => ({ exitCode, stdout: Buffer.from(stdout), stderr: Buffer.from(stderr) }),
    });
    assert.equal(invoke(print, 113, "", "Could not find service"), "");
    assert.equal(invoke(print, 0, "path = mock-generated.plist\n", ""), "path = mock-generated.plist\n");
    for (const [args, exit, stderr, absent] of [
        [print, 5, "Could not find service; mock private detail", true],
        [print, 113, "mock permission failure", true],
        [print, 113, "Could not find service", false],
        [["launchctl", "bootout", print[2]], 113, "Could not find service", true],
        [["plutil", "-lint", "mock.plist"], 113, "Could not find service", true],
        [print, null, "mock command timed out", true],
    ]) {
        assert.throws(() => invoke(args, exit, "", stderr, absent), error =>
            /native .* failed/.test(error.message) && !error.message.includes(stderr));
    }
    assert.throws(() => invoke(print, 0, "", ""), /empty service state/);
    assert.equal(runNative(print, { timeoutMs: 37, spawn: (args, options) => {
        assert.deepEqual(args, print);
        assert.equal(options.timeout, 37);
        return { exitCode: 0, stdout: Buffer.from("path = mock-generated.plist\n"), stderr: Buffer.alloc(0) };
    } }), "path = mock-generated.plist\n");
});

